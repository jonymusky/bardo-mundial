const KEY = 'bardo.lang';
let lang: Lang = 'es';

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'es' || saved === 'en' || saved === 'pt') return saved;
  } catch { /* sin storage */ }
  const nav = typeof navigator !== 'undefined' ? (navigator.language || 'es').slice(0, 2).toLowerCase() : 'es';
  return nav === 'en' || nav === 'pt' ? nav : 'es';
}
lang = detect();
if (typeof document !== 'undefined') document.documentElement.lang = lang;

export function getLang(): Lang {
  return lang;
}
export function setLang(l: Lang): void {
  lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* ignorar */ }
  document.documentElement.lang = l;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = STR[lang][key] ?? es[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}
export function tl(key: string): string[] {
  return LISTS[lang][key] ?? LISTS.es[key] ?? [];
}
export function weaponName(id: string): string {
  return t(`w.${id}`).split('|')[0];
}
export function weaponDesc(id: string): string {
  return t(`w.${id}`).split('|')[1] ?? '';
}
export function countryName(code: string, fallback: string): string {
  try {
    return new Intl.DisplayNames([lang], { type: 'region' }).of(code) ?? fallback;
  } catch {
    return fallback;
  }
}
